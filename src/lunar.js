function lYearDays(year) {
  let sum = 348;
  for (let mask = 0x8000; mask > 0x8; mask >>= 1) sum += (LUNAR_INFO[year - 1900] & mask) ? 1 : 0;
  return sum + lLeapDays(year);
}

function lLeapMonth(year) {
  return LUNAR_INFO[year - 1900] & 0xf;
}

function lLeapDays(year) {
  if (lLeapMonth(year)) return (LUNAR_INFO[year - 1900] & 0x10000) ? 30 : 29;
  return 0;
}

function lMonthDays(year, month) {
  return (LUNAR_INFO[year - 1900] & (0x10000 >> month)) ? 30 : 29;
}

// 公历 → 农历。入参为 1 基月份（moment.month()+1）。越界年份返回 null。
function solarToCockpitLunar(year, month, day) {
  if (year < 1901 || year > 2099) return null;
  let offset = Math.floor((Date.UTC(year, month - 1, day) - Date.UTC(1900, 0, 31)) / 86400000);
  let lunarYear = 1900;
  let temp;
  // 注意：lunarYear 必须随循环推进，否则所有查表都停留在起始年。
  // 循环体最后一次执行时 lunarYear 即为目标农历年；offset 恰好为 0 时
  // 该日是这一年腊月的最后一天，同样无需回退（与参考实现的 i-- 写法不同）。
  for (let y = 1900; y < 2101 && offset > 0; y++) { temp = lYearDays(y); offset -= temp; lunarYear = y; }
  if (offset < 0) { offset += temp; }
  const leap = lLeapMonth(lunarYear);
  let isLeap = false;
  let lunarMonth = 1;
  for (; lunarMonth < 13 && offset > 0; lunarMonth++) {
    if (leap > 0 && lunarMonth === leap + 1 && !isLeap) { --lunarMonth; isLeap = true; temp = lLeapDays(lunarYear); }
    else temp = lMonthDays(lunarYear, lunarMonth);
    if (isLeap && lunarMonth === leap + 1) isLeap = false;
    offset -= temp;
  }
  if (offset === 0 && leap > 0 && lunarMonth === leap + 1) {
    if (isLeap) isLeap = false;
    else { isLeap = true; --lunarMonth; }
  }
  if (offset < 0) { offset += temp; --lunarMonth; }
  return { year:lunarYear, month:lunarMonth, day:offset + 1, isLeap };
}

